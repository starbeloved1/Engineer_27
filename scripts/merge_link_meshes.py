#!/usr/bin/env python3
"""Archive the CAD export and rebuild one binary visual STL per URDF link.

Uses only NumPy and the standard library. Run from any working directory;
the default assets directory is relative to this script, not the shell.
The CLI rebuilds into source/merged_regenerated by default, keeping the active
lightweight visuals and the first merged archive intact.
"""

from __future__ import annotations

import argparse
import copy
import hashlib
import json
import math
import os
from pathlib import Path
import re
import shutil
import struct
import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET

import numpy as np


TRIANGLE = np.dtype([
    ("normal", "<f4", (3,)),
    ("vertices", "<f4", (3, 3)),
    ("attribute", "<u2"),
])
TOLERANCE = 1e-6  # metres; Euclidean error of each vertex
ARCHIVE_MANIFEST = "archive_manifest.json"


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def snapshot(path: Path) -> dict:
    return {"bytes": path.stat().st_size, "sha256": sha256(path)}


def runtime_directory(assets: Path) -> Path:
    """原始归档仍在 assets/source，当前机械臂模型放在 assets/engineer。"""
    return assets / 'engineer' if (assets / 'engineer').is_dir() else assets


def ensure_archive(assets: Path) -> dict:
    """Create a checked archive once; never replace an existing archive."""
    archive = assets / "source"
    runtime = runtime_directory(assets)
    if not archive.exists():
        original = runtime / "arm.urdf"
        if not original.is_file():
            raise FileNotFoundError(original)
        meshes = sorted(
            path for path in (runtime / "meshes").rglob("*")
            if path.is_file() and path.suffix.lower() == ".stl"
        )
        if not meshes:
            raise ValueError("No original STL meshes to archive")
        originals = [original, *meshes]
        manifest = {str(path.relative_to(runtime)): snapshot(path) for path in originals}
        with tempfile.TemporaryDirectory(prefix=".archive-", dir=assets) as temporary:
            staging = Path(temporary) / "source"
            staging.mkdir()
            for path in originals:
                relative = path.relative_to(runtime)
                destination = staging / relative
                destination.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(path, destination)
                if snapshot(destination) != manifest[str(relative)]:
                    raise ValueError(f"Archive copy differs: {relative}")
                if snapshot(path) != manifest[str(relative)]:
                    raise ValueError(f"Input changed during archiving: {relative}")
            (staging / ARCHIVE_MANIFEST).write_text(
                json.dumps({"files": manifest}, ensure_ascii=False, indent=2) + "\n",
                encoding="utf-8",
            )
            staging.rename(archive)
        print(f"Archived original URDF and {len(meshes)} STL files", flush=True)

    manifest = json.loads((archive / ARCHIVE_MANIFEST).read_text(encoding="utf-8"))["files"]
    for relative, expected in manifest.items():
        path = archive / relative
        if not path.is_file():
            raise FileNotFoundError(f"Archived input missing: {path}")
        if snapshot(path) != expected:
            raise ValueError(f"Archived input changed: {path}")
    return manifest


def vector(text: str | None, default: str) -> np.ndarray:
    result = np.asarray([float(value) for value in (text or default).split()])
    if result.shape != (3,) or not np.isfinite(result).all():
        raise ValueError(f"Invalid xyz/rpy/scale: {text}")
    return result


def rotation(rpy: np.ndarray) -> np.ndarray:
    roll, pitch, yaw = rpy
    cr, sr = math.cos(roll), math.sin(roll)
    cp, sp = math.cos(pitch), math.sin(pitch)
    cy, sy = math.cos(yaw), math.sin(yaw)
    return np.array([
        [cy * cp, cy * sp * sr - sy * cr, cy * sp * cr + sy * sr],
        [sy * cp, sy * sp * sr + cy * cr, sy * sp * cr - cy * sr],
        [-sp, cp * sr, cp * cr],
    ])


def triangle_count(path: Path) -> int:
    with path.open("rb") as stream:
        header = stream.read(84)
    if len(header) != 84:
        raise ValueError(f"Truncated binary STL: {path}")
    count = struct.unpack_from("<I", header, 80)[0]
    if path.stat().st_size != 84 + 50 * count or count == 0:
        raise ValueError(f"Invalid or unsupported binary STL: {path}")
    return count


def visual_specs(link: ET.Element, source: Path) -> list:
    specs = []
    materials = []
    for visual in link.findall("visual"):
        geometry = visual.find("geometry")
        mesh = visual.find("geometry/mesh")
        if geometry is None or mesh is None or len(geometry) != 1:
            raise ValueError("This converter requires mesh-only visuals")
        filename = mesh.get("filename", "")
        if not filename or "://" in filename or Path(filename).is_absolute():
            raise ValueError(f"Expected a local relative mesh path: {filename}")
        path = (source.parent / filename).resolve()
        if not path.is_relative_to(source.parent.resolve()):
            raise ValueError(f"Mesh is outside the source archive: {filename}")
        if not path.is_file():
            raise FileNotFoundError(path)
        origin = visual.find("origin")
        xyz = vector(origin.get("xyz") if origin is not None else None, "0 0 0")
        rpy = vector(origin.get("rpy") if origin is not None else None, "0 0 0")
        scale = vector(mesh.get("scale"), "1 1 1")
        if np.any(scale <= 0):
            raise ValueError("Non-positive mesh scale is not supported")
        specs.append((path, triangle_count(path), rotation(rpy), xyz, scale))
        materials.append(visual.find("material"))
    if not specs:
        raise ValueError(f"Link has no visual mesh: {link.get('name')}")
    # STL cannot represent different URDF materials in a single visual.
    signatures = [semantic(material) if material is not None else None for material in materials]
    if any(signature != signatures[0] for signature in signatures):
        raise ValueError(f"Different visual materials would be lost: {link.get('name')}")
    return specs


def semantic(element: ET.Element) -> tuple:
    """Compare XML meaning independently of indentation and attribute order."""
    return (
        element.tag, tuple(sorted(element.attrib.items())), (element.text or "").strip(),
        tuple(semantic(child) for child in element),
    )


def nonvisual_tree(root: ET.Element) -> tuple:
    root = copy.deepcopy(root)
    for link in root.findall("link"):
        for visual in link.findall("visual"):
            link.remove(visual)
    return semantic(root)


def expected_vertices(records: np.ndarray, spec: tuple) -> np.ndarray:
    _, _, R, xyz, scale = spec
    points = records["vertices"].astype(np.float64) * scale
    points = points @ R.T + xyz
    if not np.isfinite(points).all():
        raise ValueError(f"Non-finite vertices in {spec[0]}")
    return points


def chunks(spec: tuple, chunk_size: int):
    path, count, *_ = spec
    with path.open("rb") as stream:
        stream.seek(84)
        remaining = count
        while remaining:
            size = min(remaining, chunk_size)
            records = np.fromfile(stream, dtype=TRIANGLE, count=size)
            if len(records) != size:
                raise ValueError(f"Truncated input while reading: {path}")
            yield records
            remaining -= size


def merge_mesh(name: str, specs: list, destination: Path, chunk_size: int) -> int:
    count = sum(spec[1] for spec in specs)
    if count > 0xFFFFFFFF:
        raise ValueError(f"Binary STL triangle count overflow: {name}")
    with destination.open("wb") as stream:
        stream.write(f"Engineer_27 visual {name}".encode("ascii").ljust(80, b"\0"))
        stream.write(struct.pack("<I", count))
        for spec in specs:
            for records in chunks(spec, chunk_size):
                output = np.zeros(len(records), dtype=TRIANGLE)
                output["vertices"] = expected_vertices(records, spec)
                points = output["vertices"].astype(np.float64)
                normals = np.cross(points[:, 1] - points[:, 0], points[:, 2] - points[:, 0])
                lengths = np.linalg.norm(normals, axis=1)
                np.divide(normals, lengths[:, None], out=normals, where=lengths[:, None] > 0)
                output["normal"] = normals  # Degenerate triangles remain, with zero normals.
                output["attribute"] = records["attribute"]
                output.tofile(stream)
    return count


def verify_mesh(specs: list, destination: Path, chunk_size: int) -> dict:
    """Read output back and check every source instance, vertex and face."""
    count = sum(spec[1] for spec in specs)
    if triangle_count(destination) != count:
        raise ValueError(f"Triangle count differs: {destination}")
    source_min = np.full(3, np.inf)
    source_max = np.full(3, -np.inf)
    output_min, output_max = source_min.copy(), source_max.copy()
    max_error = 0.0
    degenerate = 0
    with destination.open("rb") as stream:
        stream.seek(84)
        for spec in specs:
            for records in chunks(spec, chunk_size):
                expected = expected_vertices(records, spec)
                actual = np.fromfile(stream, dtype=TRIANGLE, count=len(records))
                if len(actual) != len(records):
                    raise ValueError(f"Truncated output: {destination}")
                points = actual["vertices"].astype(np.float64)
                error = float(np.linalg.norm(points - expected, axis=2).max())
                max_error = max(max_error, error)
                if error > TOLERANCE or not np.isfinite(points).all():
                    raise ValueError(f"Geometry error exceeds 1 micrometre: {destination}")
                if not np.array_equal(records["attribute"], actual["attribute"]):
                    raise ValueError(f"Triangle attributes differ: {destination}")
                normals = np.cross(points[:, 1] - points[:, 0], points[:, 2] - points[:, 0])
                lengths = np.linalg.norm(normals, axis=1)
                degenerate += int(np.count_nonzero(lengths == 0))
                np.divide(normals, lengths[:, None], out=normals, where=lengths[:, None] > 0)
                if not np.allclose(actual["normal"], normals, rtol=1e-6, atol=1e-6):
                    raise ValueError(f"Invalid normals: {destination}")
                source_min = np.minimum(source_min, expected.min(axis=(0, 1)))
                source_max = np.maximum(source_max, expected.max(axis=(0, 1)))
                output_min = np.minimum(output_min, points.min(axis=(0, 1)))
                output_max = np.maximum(output_max, points.max(axis=(0, 1)))
    if not np.allclose([source_min, source_max], [output_min, output_max], rtol=0, atol=TOLERANCE):
        raise ValueError(f"Bounds differ: {destination}")
    return {
        "visual_instances": len(specs), "triangles": count,
        "max_vertex_error_m": max_error,
        "source_bounds_m": [source_min.tolist(), source_max.tolist()],
        "output_bounds_m": [output_min.tolist(), output_max.tolist()],
        "degenerate_triangles": degenerate,
    }


def build(source: Path, staging: Path, chunk_size: int) -> dict:
    root = ET.parse(source).getroot()
    original = copy.deepcopy(root)
    links = root.findall("link")
    names = [link.get("name", "") for link in links]
    if len(set(names)) != len(names) or any(not re.fullmatch(r"[A-Za-z0-9_.-]+", name) or name in (".", "..") for name in names):
        raise ValueError("Link names must be unique, safe STL filenames")
    # Resolve all inputs before generating any output.
    specs_by_name = {link.get("name"): visual_specs(link, source) for link in links}
    directory = staging / "meshes" / "visual"
    directory.mkdir(parents=True)
    report = {}
    for link in links:
        name = link.get("name")
        specs = specs_by_name[name]
        output = directory / f"{name}.stl"
        merge_mesh(name, specs, output, chunk_size)
        report[name] = verify_mesh(specs, output, chunk_size)
        material = copy.deepcopy(link.find("visual/material"))
        for visual in link.findall("visual"):
            link.remove(visual)
        visual = ET.SubElement(link, "visual", {"name": f"{name}_visual"})
        ET.SubElement(visual, "origin", {"xyz": "0 0 0", "rpy": "0 0 0"})
        geometry = ET.SubElement(visual, "geometry")
        ET.SubElement(geometry, "mesh", {"filename": f"meshes/visual/{name}.stl"})
        if material is not None:
            visual.append(material)
        print(f"{name}: {len(specs)} visuals -> 1 STL, {report[name]['triangles']:,} triangles, "
              f"error {report[name]['max_vertex_error_m']:.3g} m", flush=True)
    if nonvisual_tree(original) != nonvisual_tree(root):
        raise ValueError("Non-visual robot configuration changed")
    ET.indent(root, space="  ")
    destination = staging / "arm.urdf"
    ET.ElementTree(root).write(destination, encoding="utf-8", xml_declaration=True)
    parsed = ET.parse(destination).getroot()
    if nonvisual_tree(original) != nonvisual_tree(parsed):
        raise ValueError("Serialized robot configuration changed")
    for mesh in parsed.findall(".//visual/geometry/mesh"):
        if not (staging / mesh.get("filename")).is_file():
            raise FileNotFoundError(mesh.get("filename"))
    executable = shutil.which("check_urdf")
    if executable is None and Path("/opt/ros/humble/bin/check_urdf").is_file():
        executable = "/opt/ros/humble/bin/check_urdf"
    if executable is None:
        raise RuntimeError("check_urdf is required; source the ROS environment first")
    checked = subprocess.run([executable, str(destination)], capture_output=True, text=True, timeout=30)
    if checked.returncode:
        raise ValueError(f"check_urdf failed:\n{checked.stdout}\n{checked.stderr}")
    (staging / "mesh_merge_report.json").write_text(
        json.dumps({"source": "source/arm.urdf", "links": report}, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    return report


def publish(assets: Path, staging: Path) -> None:
    """Install validated output; roll back if any replacement fails."""
    targets = ["meshes/visual", "arm.urdf", "mesh_merge_report.json"]
    saved, installed = [], []
    try:
        for relative in targets:
            target = assets / relative
            target.parent.mkdir(parents=True, exist_ok=True)
            backup = staging / "previous" / relative
            if target.exists():
                backup.parent.mkdir(parents=True, exist_ok=True)
                os.replace(target, backup)
                saved.append(relative)
            os.replace(staging / relative, target)
            installed.append(relative)
    except BaseException:
        for relative in reversed(installed):
            target = assets / relative
            destination = staging / relative
            destination.parent.mkdir(parents=True, exist_ok=True)
            os.replace(target, destination)
        for relative in reversed(saved):
            os.replace(staging / "previous" / relative, assets / relative)
        raise


def clean_original_copies(assets: Path, manifest: dict) -> int:
    removed = 0
    for relative, expected in manifest.items():
        if not relative.startswith("meshes/"):
            continue
        path = runtime_directory(assets) / relative
        if path.is_file():
            # Only remove a copy whose contents are still in the checked archive.
            try:
                if snapshot(path) != expected:
                    print(f"Kept changed original mesh: {relative}", file=sys.stderr)
                    continue
                path.unlink()
                removed += 1
            except OSError as exc:
                print(f"Kept original mesh {relative}: {exc}", file=sys.stderr)
    return removed


def run(assets: Path, chunk_size: int = 100_000, output_dir: Path | None = None) -> dict:
    assets = assets.resolve()
    destination = runtime_directory(assets) if output_dir is None else output_dir.resolve()
    archive = assets / "source"
    if destination.is_relative_to(archive) and destination != archive / "merged_regenerated":
        raise ValueError("Cannot overwrite archived inputs; use source/merged_regenerated")
    if chunk_size < 1:
        raise ValueError("chunk size must be positive")
    manifest = ensure_archive(assets)
    destination.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix=".merge-", dir=destination) as temporary:
        staging = Path(temporary)
        report = build(assets / "source" / "arm.urdf", staging, chunk_size)
        # Recheck archive integrity before publishing or cleaning original copies.
        ensure_archive(assets)
        publish(destination, staging)
    removed = clean_original_copies(assets, manifest) if destination == runtime_directory(assets) else 0
    print(f"Published {len(report)} visual meshes; removed {removed} archived duplicate meshes", flush=True)
    return report


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--assets-dir", type=Path, default=Path(__file__).resolve().parents[1] / "assets")
    parser.add_argument("--chunk-triangles", type=int, default=100_000)
    parser.add_argument("--output-dir", type=Path,
                        help="Output directory; default: <assets-dir>/source/merged_regenerated")
    args = parser.parse_args()
    try:
        destination = args.output_dir or args.assets_dir / "source" / "merged_regenerated"
        run(args.assets_dir, args.chunk_triangles, destination)
    except (OSError, ValueError, RuntimeError, ET.ParseError, subprocess.TimeoutExpired) as exc:
        print(f"Merge failed: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
